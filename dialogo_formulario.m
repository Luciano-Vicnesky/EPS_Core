function respostas = dialogo_formulario(prompts, titulo, defaults, opcoes)
% DIALOGO_FORMULARIO
% Substituto responsivo para inputdlg com layout multicoluna automático
% ajustado à resolução da tela e suporte a listas suspensas (popupmenu).
%
% Entradas:
%   prompts  : cell array com os rótulos dos campos
%   titulo   : título da janela
%   defaults : cell array com os valores iniciais (texto ou número)
%   opcoes   : (opcional) cell array com listas de opções p/ dropdown;
%              use [] nos campos de digitação livre.
%
% Saída:
%   respostas : cell array (Nx1) de strings ou {} se cancelado.

N = numel(prompts);
if nargin < 4 || isempty(opcoes)
    opcoes = cell(N, 1);
end

respostas = {};

% 1. Cálculo responsivo das dimensões conforme a tela atual
scr    = get(0, 'ScreenSize'); % [x, y, largura, altura]
max_h  = round(scr(4) * 0.82);
max_w  = round(scr(3) * 0.92);

h_header = 44;
h_footer = 54;
pad_x    = 20;
pad_y    = 14;
row_h    = 54; % 18px rótulo + 2px folga + 24px caixa + 10px espaço

max_rows_tela = max(4, floor((max_h - h_header - h_footer - 2*pad_y) / row_h));
alvo_rows     = min(max_rows_tela, 8); % Acima de 8 campos divide em 2+ colunas

n_cols = max(1, ceil(N / alvo_rows));
col_w  = min(400, floor((max_w - pad_x * (n_cols + 1)) / n_cols));

% Se ficar estreito demais em tela pequena, reduz colunas e compacta altura
if col_w < 260 && n_cols > 1
    n_cols = max(1, floor((max_w - pad_x) / (260 + pad_x)));
    col_w  = min(400, floor((max_w - pad_x * (n_cols + 1)) / n_cols));
end

n_rows = ceil(N / n_cols);
if (h_header + h_footer + 2*pad_y + n_rows * row_h) > max_h
    row_h = max(40, floor((max_h - h_header - h_footer - 2*pad_y) / n_rows));
end

fig_w = max(420, n_cols * col_w + (n_cols + 1) * pad_x);
fig_h = h_header + h_footer + 2*pad_y + n_rows * row_h;

pos_x = max(10, round((scr(3) - fig_w) / 2));
pos_y = max(35, round((scr(4) - fig_h) / 2));

% 2. Criação da Janela Modal
cor_fundo = [0.96 0.97 0.98];
fig = figure( ...
    'Name', titulo, ...
    'NumberTitle', 'off', ...
    'MenuBar', 'none', ...
    'ToolBar', 'none', ...
    'Resize', 'off', ...
    'Color', cor_fundo, ...
    'Units', 'pixels', ...
    'Position', [pos_x, pos_y, fig_w, fig_h], ...
    'WindowStyle', 'modal', ...
    'CloseRequestFcn', @ao_cancelar, ...
    'WindowKeyPressFcn', @ao_teclar);

% Cabeçalho visual
uipanel('Parent', fig, ...
    'Units', 'pixels', ...
    'Position', [0, fig_h - h_header, fig_w, h_header], ...
    'BackgroundColor', [0.11 0.25 0.45], ...
    'BorderType', 'none');

uicontrol('Parent', fig, ...
    'Style', 'text', ...
    'String', titulo, ...
    'Units', 'pixels', ...
    'Position', [pad_x, fig_h - h_header + 10, fig_w - 2*pad_x, 24], ...
    'BackgroundColor', [0.11 0.25 0.45], ...
    'ForegroundColor', 'w', ...
    'FontSize', 10.5, ...
    'FontWeight', 'bold', ...
    'HorizontalAlignment', 'left');

% 3. Geração dos Campos (preenchimento coluna por coluna)
controles = gobjects(N, 1);
eh_popup  = false(N, 1);
y_topo    = fig_h - h_header - pad_y;
h_ctrl    = min(24, row_h - 22);
h_lbl     = 17;

for k = 1:N
    col = floor((k - 1) / n_rows) + 1;
    row = mod(k - 1, n_rows) + 1;

    x_col   = pad_x + (col - 1) * (col_w + pad_x);
    y_ctrl  = y_topo - row * row_h + 8;
    y_lbl   = y_ctrl + h_ctrl + 2;

    rotulo = strtrim(char(prompts{k}));
    val_def = defaults{k};
    if isnumeric(val_def)
        val_def = sprintf('%.10g', val_def);
    else
        val_def = strtrim(char(val_def));
    end

    uicontrol('Parent', fig, ...
        'Style', 'text', ...
        'String', rotulo, ...
        'TooltipString', rotulo, ...
        'Units', 'pixels', ...
        'Position', [x_col, y_lbl, col_w, h_lbl], ...
        'BackgroundColor', cor_fundo, ...
        'ForegroundColor', [0.15 0.18 0.22], ...
        'FontSize', 8.5, ...
        'FontWeight', 'bold', ...
        'HorizontalAlignment', 'left');

    if k <= numel(opcoes) && iscell(opcoes{k}) && ~isempty(opcoes{k})
        lista_opt = opcoes{k};
        idx_sel   = find(strcmpi(lista_opt, val_def), 1);
        if isempty(idx_sel)
            if ~isempty(val_def)
                lista_opt = [{val_def}, lista_opt];
            end
            idx_sel = 1;
        end
        controles(k) = uicontrol('Parent', fig, ...
            'Style', 'popupmenu', ...
            'String', lista_opt, ...
            'Value', idx_sel, ...
            'TooltipString', rotulo, ...
            'Units', 'pixels', ...
            'Position', [x_col, y_ctrl, col_w, h_ctrl], ...
            'BackgroundColor', 'w', ...
            'FontSize', 9);
        eh_popup(k) = true;
    else
        controles(k) = uicontrol('Parent', fig, ...
            'Style', 'edit', ...
            'String', val_def, ...
            'TooltipString', rotulo, ...
            'Units', 'pixels', ...
            'Position', [x_col, y_ctrl, col_w, h_ctrl], ...
            'BackgroundColor', 'w', ...
            'FontSize', 9, ...
            'HorizontalAlignment', 'left');
    end
end

% Linha divisória e botões de ação no rodapé
uipanel('Parent', fig, ...
    'Units', 'pixels', ...
    'Position', [pad_x, h_footer, fig_w - 2*pad_x, 1], ...
    'BackgroundColor', [0.80 0.83 0.87], ...
    'BorderType', 'none');

btn_w = 135;
btn_h = 32;
gap_b = 14;
x_ok  = round((fig_w - (2*btn_w + gap_b)) / 2);

uicontrol('Parent', fig, ...
    'Style', 'pushbutton', ...
    'String', 'Confirmar', ...
    'Units', 'pixels', ...
    'Position', [x_ok, 11, btn_w, btn_h], ...
    'BackgroundColor', [0.15 0.52 0.32], ...
    'ForegroundColor', 'w', ...
    'FontSize', 9.5, ...
    'FontWeight', 'bold', ...
    'Callback', @ao_confirmar);

uicontrol('Parent', fig, ...
    'Style', 'pushbutton', ...
    'String', 'Cancelar', ...
    'Units', 'pixels', ...
    'Position', [x_ok + btn_w + gap_b, 11, btn_w, btn_h], ...
    'BackgroundColor', [0.86 0.88 0.90], ...
    'ForegroundColor', [0.15 0.15 0.15], ...
    'FontSize', 9.5, ...
    'Callback', @ao_cancelar);

uiwait(fig);
if isvalid(fig)
    delete(fig);
end

    function ao_confirmar(~, ~)
        respostas = cell(N, 1);
        for i = 1:N
            if eh_popup(i)
                itens = get(controles(i), 'String');
                idx   = get(controles(i), 'Value');
                if iscell(itens)
                    respostas{i} = strtrim(char(itens{idx}));
                else
                    respostas{i} = strtrim(char(itens(idx, :)));
                end
            else
                respostas{i} = strtrim(char(get(controles(i), 'String')));
            end
        end
        uiresume(fig);
    end

    function ao_cancelar(~, ~)
        respostas = {};
        uiresume(fig);
    end

    function ao_teclar(~, evt)
        if strcmp(evt.Key, 'escape')
            ao_cancelar([], []);
        end
    end
end