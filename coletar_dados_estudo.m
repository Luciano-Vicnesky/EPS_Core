a2  = dialogo_formulario(p2, 'Parâmetros CELESC (2/2: Proteção a Montante no PC)', extrair_vals(cel, c2), op2);
if isempty(a2), disp('Operação cancelada.'); return; end

tmp = atribuir_nums(tmp, {'Ip_51','DT_51','Ip_50','t_50','Ip_51N','DT_51N','Ip_50N','t_50N'}, a2([2:5, 7:10]));
tmp.Curva_51   = upper(strtrim(a2{1}));
tmp.Curva_51N  = upper(strtrim(a2{6}));
tmp.Usa_Elo_PC = upper(strtrim(a2{11}));
tmp.Elo_PC     = upper(regexprep(strtrim(a2{12}), '\s+', ''));

if isnan(tmp.Ip_50)  || tmp.Ip_50  <= 0, tmp.Ip_50  = 0; tmp.t_50  = 0; end
if isnan(tmp.Ip_50N) || tmp.Ip_50N <= 0, tmp.Ip_50N = 0; tmp.t_50N = 0; end
if isnan(tmp.t_50)   || tmp.t_50   <  0, tmp.t_50   = 0; end
if isnan(tmp.t_50N)  || tmp.t_50N  <  0, tmp.t_50N  = 0; end

if ~ismember(tmp.Curva_51, curvas_validas) || ~ismember(tmp.Curva_51N, curvas_validas) || ...
any(isnan([tmp.Ip_51, tmp.DT_51, tmp.Ip_51N, tmp.DT_51N])) || ...
any([tmp.Ip_51, tmp.DT_51, tmp.Ip_51N, tmp.DT_51N] <= 0) || ...
~ismember(tmp.Usa_Elo_PC, {'SIM','NAO'})
errordlg('Ajustes da Celesc inválidos (curvas NI/MI/EI, pickups/diais > 0 e elo SIM/NAO).', 'Erro de Entrada');
return;
end
if strcmpi(tmp.Usa_Elo_PC, 'NAO')
tmp.Elo_PC = 'N/A';
elseif isempty(tmp.Elo_PC) || strcmpi(tmp.Elo_PC, 'N/A')
errordlg('Você habilitou Elo Fusível no PC (SIM), mas manteve o modelo como N/A. Selecione um elo válido.', 'Erro de Entrada');
return;
elseif ~ismember(tmp.Elo_PC, elos_padrao)
warndlg(sprintf('Elo "%s" fora da tabela ABNT NBR 7282. Será usada aproximação proporcional.', tmp.Elo_PC), 'Aviso de Elo');
end
ok = true;
end

