any([tmp.R1, tmp.X1, tmp.R0, tmp.X0] < 0) || ...
hypot(tmp.R1, tmp.X1) <= 0 || hypot(2*tmp.R1 + tmp.R0, 2*tmp.X1 + tmp.X0) <= 0
errordlg('Parâmetros de rede/impedância da Celesc inválidos (Z1 > 0, 2Z1+Z0 > 0 e valores >= 0).', 'Erro de Entrada');
return;
end

p2 = {'Curva de Fase Celesc no PC - 51 (NI, MI ou EI):', ...
'Pickup de Fase Celesc - Ip_51 (A):', ...
'Dial de Tempo de Fase Celesc - DT_51:', ...
'Pickup Instantâneo de Fase Celesc - Ip_50 (A | 0=Sem 50):', ...
'Tempo Instantâneo de Fase Celesc - t_50 (s | 0=Sem 50):', ...
'Curva de Neutro Celesc no PC - 51N (NI, MI ou EI):', ...
'Pickup de Neutro Celesc - Ip_51N (A):', ...
'Dial de Tempo de Neutro Celesc - DT_51N:', ...
'Pickup Instantâneo de Neutro Celesc - Ip_50N (A | 0=Sem 50N):', ...
