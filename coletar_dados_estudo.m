function [cel, cli, cfg, ok] = coletar_dados_estudo(arquivo_mat)
% COLETAR_DADOS_ESTUDO
% Carrega ou inicializa o arquivo .mat (dados_concessionaria, dados_cliente,
% dados_calculo), coleta atualizações via dialogo_formulario e valida todas
% as entradas do estudo.

ok = false;
elos_padrao    = {'0.5H','1H','2H','3H','5H','6K','8K','10K','12K','15K','20K','25K','30K','40K','50K','65K','80K','100K','140K','200K'};
curvas_validas = {'NI', 'MI', 'EI'};

[def_cel, def_cli, def_cfg] = padroes_sistema();
if ~isfile(arquivo_mat)
cel = def_cel; cli = def_cli; cfg = def_cfg;
salvar_estado(arquivo_mat, cel, cli, cfg);
else
S = load(arquivo_mat);
if isfield(S, 'dados_concessionaria'), [cel, m1] = mesclar_padroes(S.dados_concessionaria, def_cel); else, cel = def_cel; m1 = true; end
if isfield(S, 'dados_cliente'),        [cli, m2] = mesclar_padroes(S.dados_cliente,        def_cli); else, cli = def_cli; m2 = true; end
if isfield(S, 'dados_calculo'),        [cfg, m3] = mesclar_padroes(S.dados_calculo,        def_cfg); else, cfg = def_cfg; m3 = true; end
if m1 || m2 || m3, salvar_estado(arquivo_mat, cel, cli, cfg); end
end

% 1. Concessionária (Celesc)
[upd, canc] = perguntar_atualizar('Deseja atualizar os Parâmetros da CELESC (Impedâncias e Proteção no PC)?', 'Dados da Concessionária');
if canc, disp('Operação cancelada.'); return; end
if upd
[cel_novo, ok_cel] = editar_celesc(cel, curvas_validas, elos_padrao);
if ~ok_cel, return; end
cel = cel_novo;
salvar_estado(arquivo_mat, cel, cli, cfg);
end

% 2. Cliente, Infraestrutura, TC, TP de Proteção e TPA
[upd, canc] = perguntar_atualizar('Deseja atualizar os Dados do Cliente, TCs e TPs?', 'Dados do Projeto');
if canc, disp('Operação cancelada.'); return; end
if upd
[cli_novo, ok_cli] = editar_cliente(cli);
if ~ok_cli, return; end
cli = cli_novo;
salvar_estado(arquivo_mat, cel, cli, cfg);
end

% 3. Parâmetros Normativos e de Cálculo
[upd, canc] = perguntar_atualizar('Deseja revisar/atualizar os Parâmetros e Critérios Normativos de Cálculo?', 'Dados de Cálculo');
if canc, disp('Operação cancelada.'); return; end
if upd
[cfg_novo, ok_cfg] = editar_calculo(cfg);
if ~ok_cfg, return; end
cfg = cfg_novo;
salvar_estado(arquivo_mat, cel, cli, cfg);
end

% 4. Validação de integridade final dos dados carregados
kVA   = lib_eletrica.parse_vetor_num(cli.Trafos_kVA);
Z_pct = lib_eletrica.parse_vetor_num(cli.Z_Trafos_pct);
tipos = strsplit(upper(strtrim(cli.Tipos_Trafos)));
if isempty(kVA) || any(isnan([kVA, Z_pct])) || any([kVA, Z_pct] <= 0) || ...
length(kVA) ~= length(Z_pct) || length(kVA) ~= length(tipos) || ~all(ismember(tipos, {'O','S'}))
errordlg('Erro: Vetores de potências, impedâncias e tipos dos transformadores inconsistentes.', 'Erro de Dados');
return;
end
if ~ismember(upper(strtrim(cel.Curva_51)), curvas_validas) || ~ismember(upper(strtrim(cel.Curva_51N)), curvas_validas) || ...
(strcmpi(strtrim(cel.Usa_Elo_PC), 'SIM') && (isempty(strtrim(cel.Elo_PC)) || strcmpi(strtrim(cel.Elo_PC), 'N/A')))
errordlg('Erro: Dados da Celesc salvos inválidos (verifique curvas NI/MI/EI e modelo do Elo no PC).', 'Erro de Dados');
return;
end

ok = true;
end

