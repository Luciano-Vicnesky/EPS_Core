'Reatância de Seq. Zero no PC - X0 (p.u.):', ...
'Resistência de Falta Padrão - Rf (Ohms):'};
c1 = {'Vbase_kV','Sbase_MVA','R1','X1','R0','X0','Rf'};
a1 = dialogo_formulario(p1, 'Parâmetros CELESC (1/2: Base e Impedâncias no PC)', extrair_vals(cel, c1));
if isempty(a1), disp('Operação cancelada.'); return; end
