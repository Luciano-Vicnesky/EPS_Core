function [s, mudou] = mesclar_padroes(s, def)
mudou = false;
fn = fieldnames(def);
for k = 1:numel(fn)
if ~isfield(s, fn{k}), s.(fn{k}) = def.(fn{k}); mudou = true; end
end
fn_s = fieldnames(s);
for k = 1:numel(fn_s)
if ~isfield(def, fn_s{k}), s = rmfield(s, fn_s{k}); mudou = true; end
end
end

function vals = extrair_vals(s, campos)
vals = cell(numel(campos), 1);
for k = 1:numel(campos)
v = s.(campos{k});
if isnumeric(v), vals{k} = sprintf('%.10g', v); else, vals{k} = char(v); end
end
end

function s = atribuir_nums(s, campos, resps)
for k = 1:numel(campos)
s.(campos{k}) = str2double(strrep(strtrim(resps{k}), ',', '.'));
end
